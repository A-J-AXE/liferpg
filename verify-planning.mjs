import assert from "node:assert/strict";
import {planOf,applyPlan,columns,belongs,addDays,monday,upcomingHTML} from "./ui/planning.mjs";
const today="2026-11-04",week=monday(today);
const task={id:"one",title:"Project task",project:"alpha",date:"",time:"",children:[],minutes:"30",done:false};
applyPlan(task,"month","2026-12-15");
assert.equal(task.date,"");assert.equal(task.time,"");assert.equal(task.project,"alpha");
assert.deepEqual(planOf(task),{kind:"month",value:"2026-12"});
const overview=columns("Overview",today,today);
assert.equal(overview.length,6);
assert.deepEqual(overview.filter(c=>belongs(task,c,"Overview",today)).map(c=>c.id),["nextMonth"]);
applyPlan(task,"week",addDays(week,7));assert.equal(task.date,"");
assert.deepEqual(overview.filter(c=>belongs(task,c,"Overview",today)).map(c=>c.id),["nextWeek"]);
applyPlan(task,"day",today);
assert.deepEqual(overview.filter(c=>belongs(task,c,"Overview",today)).map(c=>c.id),["today"]);
applyPlan(task,"exact-time",today,"14:30");assert.equal(task.time,"14:30");
applyPlan(task,"someday");assert.equal(task.date,"");assert.equal(task.time,"");
assert.deepEqual(overview.filter(c=>belongs(task,c,"Overview",today)).map(c=>c.id),["someday"]);
assert.equal(columns("Day",today,today).length,7);
assert.equal(columns("Week",today,today).length,5);
assert.equal(columns("Month",today,today).length,5);
assert.equal(planOf({date:"2026-11-05",time:"10:00"}).kind,"exact-time");
assert.equal(planOf({date:"",time:""}).kind,"unscheduled");
const html=upcomingHTML({tasks:[task],mode:"Overview",anchor:today,today,renderTask:t=>'<div data-task="'+t.id+'">'+t.title+"</div>"});
assert.match(html,/Someday/);assert.match(html,/data-plan-kind="someday"/);
assert.equal((html.match(/data-task="one"/g)||[]).length,1);
console.log("PASS: task precision, bucket placement, no duplicate task rendering");
